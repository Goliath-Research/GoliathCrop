-- GoliathCrop Phase 5 — lab samples (omics hooks), sibling product link tables
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_lab;

CREATE TABLE IF NOT EXISTS crop_lab.samples (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id integer NOT NULL REFERENCES crop_core.fields (id) ON DELETE CASCADE,
  plot_id integer REFERENCES crop_core.plots (id) ON DELETE SET NULL,
  kind text NOT NULL DEFAULT 'soil',
  collected_on date NOT NULL DEFAULT CURRENT_DATE,
  depth_cm double precision,
  geom geometry(Point, 4326),
  omics_run_ref text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT samples_kind_chk CHECK (kind IN ('soil', 'tissue', 'other'))
);

CREATE INDEX IF NOT EXISTS samples_field_collected_idx
  ON crop_lab.samples (field_id, collected_on DESC);

CREATE TABLE IF NOT EXISTS crop_lab.sample_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sample_id bigint NOT NULL REFERENCES crop_lab.samples (id) ON DELETE CASCADE,
  analyte text NOT NULL,
  value double precision,
  unit text,
  measured_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE VIEW crop_lab.v_sample AS
SELECT
  s.id AS sample_id,
  s.field_id,
  s.plot_id,
  s.kind,
  s.collected_on,
  s.depth_cm,
  CASE WHEN s.geom IS NOT NULL THEN ST_AsGeoJSON(s.geom)::text ELSE NULL END AS geo_json,
  s.omics_run_ref,
  MAX(CASE WHEN sr.analyte = 'N' THEN sr.value END) AS n_ppm,
  MAX(CASE WHEN sr.analyte = 'P' THEN sr.value END) AS p_ppm,
  MAX(CASE WHEN sr.analyte = 'K' THEN sr.value END) AS k_ppm,
  MAX(CASE WHEN sr.analyte = 'pH' THEN sr.value END) AS ph,
  MAX(CASE WHEN sr.analyte = 'OM' THEN sr.value END) AS om_pct
FROM crop_lab.samples s
LEFT JOIN crop_lab.sample_results sr ON sr.sample_id = s.id
GROUP BY
  s.id,
  s.field_id,
  s.plot_id,
  s.kind,
  s.collected_on,
  s.depth_cm,
  s.geom,
  s.omics_run_ref;

ALTER TABLE crop_lab.samples ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_lab.sample_results ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS samples_field_access ON crop_lab.samples;
CREATE POLICY samples_field_access ON crop_lab.samples
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_core.fields fld
      WHERE fld.id = field_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

DROP POLICY IF EXISTS sample_results_access ON crop_lab.sample_results;
CREATE POLICY sample_results_access ON crop_lab.sample_results
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_lab.samples s
      INNER JOIN crop_core.fields fld ON fld.id = s.field_id
      WHERE s.id = sample_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

CREATE OR REPLACE FUNCTION crop_lab.fn_semantic_sample_list_by_field(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS SETOF crop_lab.v_sample
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_lab, crop_core, portal, pg_temp
AS $$
DECLARE
  v_field_id integer;
  v_kind text;
  v_from date;
  v_to date;
BEGIN
  v_field_id := NULLIF(p_params->>'field_id', '')::integer;
  IF v_field_id IS NULL THEN
    RAISE EXCEPTION 'field_id is required';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.fields fld
    INNER JOIN crop_core.farms f ON f.id = fld.farm_id
    WHERE fld.id = v_field_id
      AND (
        f.organization_id = ANY (portal.fn_semantic_user_organization_ids(p_user_id))
        OR EXISTS (
          SELECT 1 FROM crop_core.farm_members m
          WHERE m.farm_id = f.id AND m.user_id = p_user_id
        )
      )
  ) THEN
    RETURN;
  END IF;
  v_kind := NULLIF(p_params->>'kind', '');
  v_from := NULLIF(p_params->>'from', '')::date;
  v_to := NULLIF(p_params->>'to', '')::date;

  RETURN QUERY
  SELECT v.*
  FROM crop_lab.v_sample v
  WHERE v.field_id = v_field_id
    AND (v_kind IS NULL OR v.kind = v_kind)
    AND (v_from IS NULL OR v.collected_on >= v_from)
    AND (v_to IS NULL OR v.collected_on <= v_to)
  ORDER BY v.collected_on DESC, v.sample_id DESC
  LIMIT GREATEST(1, LEAST(COALESCE(p_limit, 500), 500));
END;
$$;

CREATE OR REPLACE FUNCTION crop_lab.sp_link_omics_run(
  p_user_id integer,
  p_sample_id bigint,
  p_omics_run_ref text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_lab, crop_core, pg_temp
AS $$
BEGIN
  PERFORM set_config('goliath.crop.user_id', COALESCE(p_user_id::text, ''), true);
  UPDATE crop_lab.samples s
  SET omics_run_ref = NULLIF(btrim(p_omics_run_ref), '')
  WHERE s.id = p_sample_id
    AND EXISTS (
      SELECT 1
      FROM crop_core.fields fld
      WHERE fld.id = s.field_id
        AND crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
    );
  IF NOT FOUND THEN
    RAISE EXCEPTION 'sample not found or not accessible';
  END IF;
END;
$$;

