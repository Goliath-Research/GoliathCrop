CREATE OR REPLACE VIEW crop_core.v_plot AS
SELECT
  p.id,
  p.field_id,
  p.trial_id,
  p.code,
  p.omics_run_ref,
  CASE
    WHEN p.geom IS NULL THEN NULL
    ELSE ST_AsGeoJSON(p.geom)::text
  END AS geometry
FROM crop_core.plots p;

