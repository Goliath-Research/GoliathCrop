CREATE OR REPLACE FUNCTION crop_link.fn_semantic_groundstation_by_field(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  link_id bigint,
  field_id integer,
  external_flight_ref text,
  telemetry_uri text,
  imagery_uri text,
  source_product text,
  registered_at timestamptz,
  notes text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_link, crop_core, portal, pg_temp
AS $$
DECLARE
  v_field_id integer;
BEGIN
  v_field_id := NULLIF(p_params->>'field_id', '')::integer;
  IF v_field_id IS NULL THEN
    RAISE EXCEPTION 'field_id is required';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.fields fld
    INNER JOIN crop_core.farms f ON f.id = fld.farm_id
    WHERE fld.id = v_field_id
      AND (
        f.organization_id = ANY (portal.fn_semantic_user_organization_ids(p_user_id))
        OR EXISTS (
          SELECT 1 FROM crop_core.farm_members m
          WHERE m.farm_id = f.id AND m.user_id = p_user_id
        )
      )
  ) THEN
    RETURN;
  END IF;

  RETURN QUERY
  SELECT
    g.id,
    g.field_id,
    g.external_flight_ref,
    g.telemetry_uri,
    g.imagery_uri,
    g.source_product,
    g.registered_at,
    g.notes
  FROM crop_link.groundstation_flights g
  WHERE g.field_id = v_field_id
  ORDER BY g.registered_at DESC
  LIMIT GREATEST(1, LEAST(COALESCE(p_limit, 200), 200));
END;
$$;

CREATE OR REPLACE FUNCTION crop_link.sp_register_groundstation_flight(
  p_user_id integer,
  p_field_id integer,
  p_external_flight_ref text,
  p_telemetry_uri text DEFAULT NULL,
  p_imagery_uri text DEFAULT NULL,
  p_notes text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_link, crop_core, crop_img, crop_wf, pg_temp
AS $$
DECLARE
  v_id bigint;
BEGIN
  PERFORM set_config('goliath.crop.user_id', COALESCE(p_user_id::text, ''), true);
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.fields fld
    WHERE fld.id = p_field_id
      AND crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
  ) THEN
    RAISE EXCEPTION 'field not accessible';
  END IF;
  INSERT INTO crop_link.groundstation_flights (
    field_id,
    external_flight_ref,
    telemetry_uri,
    imagery_uri,
    notes
  )
  VALUES (
    p_field_id,
    btrim(p_external_flight_ref),
    NULLIF(btrim(p_telemetry_uri), ''),
    NULLIF(btrim(p_imagery_uri), ''),
    p_notes
  )
  ON CONFLICT (field_id, external_flight_ref) DO UPDATE SET
    telemetry_uri = COALESCE(EXCLUDED.telemetry_uri, crop_link.groundstation_flights.telemetry_uri),
    imagery_uri = COALESCE(EXCLUDED.imagery_uri, crop_link.groundstation_flights.imagery_uri),
    notes = COALESCE(EXCLUDED.notes, crop_link.groundstation_flights.notes)
  RETURNING id INTO v_id;

  IF p_imagery_uri IS NOT NULL AND btrim(p_imagery_uri) <> '' THEN
    PERFORM crop_img.sp_register_drone_upload(
      p_user_id,
      p_field_id,
      btrim(p_imagery_uri),
      NULL,
      NULL
    );
  END IF;

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION crop_core.sp_link_plot_omics_run(
  p_user_id integer,
  p_plot_id integer,
  p_omics_run_ref text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_core, pg_temp
AS $$
BEGIN
  UPDATE crop_core.plots p
  SET omics_run_ref = NULLIF(btrim(p_omics_run_ref), '')
  WHERE p.id = p_plot_id
    AND EXISTS (
      SELECT 1
      FROM crop_core.fields fld
      WHERE fld.id = p.field_id
        AND crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
    );
  IF NOT FOUND THEN
    RAISE EXCEPTION 'plot not found or not accessible';
  END IF;
END;
$$;
