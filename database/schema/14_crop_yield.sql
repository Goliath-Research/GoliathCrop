-- GoliathCrop Phase 5 — measured yield, predictions, semantic reads, weekly backlog
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_yield;

CREATE TABLE IF NOT EXISTS crop_yield.yields (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planting_id integer NOT NULL REFERENCES crop_core.plantings (id) ON DELETE CASCADE,
  measured_t_ha double precision NOT NULL,
  measured_on date NOT NULL DEFAULT CURRENT_DATE,
  source text NOT NULL DEFAULT 'manual',
  notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS yields_planting_measured_idx
  ON crop_yield.yields (planting_id, measured_on DESC);

CREATE TABLE IF NOT EXISTS crop_yield.predictions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planting_id integer NOT NULL REFERENCES crop_core.plantings (id) ON DELETE CASCADE,
  predicted_t_ha double precision NOT NULL,
  model_version text NOT NULL DEFAULT 'baseline-cpu-v1',
  model_backend text NOT NULL DEFAULT 'cpu',
  predicted_at timestamptz NOT NULL DEFAULT now(),
  run_id uuid NOT NULL DEFAULT gen_random_uuid(),
  CONSTRAINT predictions_backend_chk CHECK (model_backend IN ('cpu', 'runpod'))
);

CREATE INDEX IF NOT EXISTS predictions_planting_predicted_idx
  ON crop_yield.predictions (planting_id, predicted_at DESC);

CREATE OR REPLACE VIEW crop_yield.v_yield AS
SELECT
  pl.id AS planting_id,
  pl.season_id,
  pl.field_id,
  (
    SELECT y.measured_t_ha
    FROM crop_yield.yields y
    WHERE y.planting_id = pl.id
    ORDER BY y.measured_on DESC, y.id DESC
    LIMIT 1
  ) AS measured_t_ha,
  (
    SELECT p.predicted_t_ha
    FROM crop_yield.predictions p
    WHERE p.planting_id = pl.id
    ORDER BY p.predicted_at DESC, p.id DESC
    LIMIT 1
  ) AS predicted_t_ha,
  (
    SELECT p.model_version
    FROM crop_yield.predictions p
    WHERE p.planting_id = pl.id
    ORDER BY p.predicted_at DESC, p.id DESC
    LIMIT 1
  ) AS model_version,
  (
    SELECT p.predicted_at
    FROM crop_yield.predictions p
    WHERE p.planting_id = pl.id
    ORDER BY p.predicted_at DESC, p.id DESC
    LIMIT 1
  ) AS predicted_at
FROM crop_core.plantings pl;

ALTER TABLE crop_yield.yields ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_yield.predictions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS yields_planting_access ON crop_yield.yields;
CREATE POLICY yields_planting_access ON crop_yield.yields
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_core.plantings pl
      INNER JOIN crop_core.fields fld ON fld.id = pl.field_id
      WHERE pl.id = planting_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

DROP POLICY IF EXISTS predictions_planting_access ON crop_yield.predictions;
CREATE POLICY predictions_planting_access ON crop_yield.predictions
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_core.plantings pl
      INNER JOIN crop_core.fields fld ON fld.id = pl.field_id
      WHERE pl.id = planting_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

CREATE OR REPLACE FUNCTION crop_yield.fn_semantic_yield_by_season(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  planting_id integer,
  season_id integer,
  field_id integer,
  measured_t_ha double precision,
  predicted_t_ha double precision,
  model_version text,
  predicted_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_yield, crop_core, portal, pg_temp
AS $$
DECLARE
  v_season_id integer;
BEGIN
  v_season_id := NULLIF(p_params->>'season_id', '')::integer;
  IF v_season_id IS NULL THEN
    RAISE EXCEPTION 'season_id is required';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.seasons s
    INNER JOIN crop_core.farms f ON f.id = s.farm_id
    WHERE s.id = v_season_id
      AND (
        f.organization_id = ANY (portal.fn_semantic_user_organization_ids(p_user_id))
        OR EXISTS (
          SELECT 1 FROM crop_core.farm_members m
          WHERE m.farm_id = f.id AND m.user_id = p_user_id
        )
      )
  ) THEN
    RETURN;
  END IF;

  RETURN QUERY
  SELECT
    y.planting_id,
    y.season_id,
    y.field_id,
    y.measured_t_ha,
    y.predicted_t_ha,
    y.model_version,
    y.predicted_at
  FROM crop_yield.v_yield y
  WHERE y.season_id = v_season_id
  ORDER BY y.field_id, y.planting_id
  LIMIT GREATEST(1, LEAST(COALESCE(p_limit, 500), 500));
END;
$$;

CREATE OR REPLACE FUNCTION crop_yield.sp_upsert_measured(
  p_user_id integer,
  p_planting_id integer,
  p_measured_t_ha double precision,
  p_measured_on date DEFAULT CURRENT_DATE,
  p_source text DEFAULT 'import',
  p_notes text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_yield, crop_core, pg_temp
AS $$
DECLARE
  v_id bigint;
BEGIN
  PERFORM set_config('goliath.crop.user_id', COALESCE(p_user_id::text, ''), true);
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.plantings pl
    INNER JOIN crop_core.fields fld ON fld.id = pl.field_id
    WHERE pl.id = p_planting_id
      AND crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
  ) THEN
    RAISE EXCEPTION 'planting not accessible';
  END IF;
  INSERT INTO crop_yield.yields (planting_id, measured_t_ha, measured_on, source, notes)
  VALUES (p_planting_id, p_measured_t_ha, COALESCE(p_measured_on, CURRENT_DATE), COALESCE(p_source, 'import'), p_notes)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION crop_yield.sp_store_prediction(
  p_planting_id integer,
  p_predicted_t_ha double precision,
  p_model_version text,
  p_model_backend text DEFAULT 'cpu',
  p_run_id uuid DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_yield, crop_core, pg_temp
AS $$
DECLARE
  v_id bigint;
BEGIN
  IF p_model_backend IS NULL OR p_model_backend NOT IN ('cpu', 'runpod') THEN
    p_model_backend := 'cpu';
  END IF;
  INSERT INTO crop_yield.predictions (
    planting_id,
    predicted_t_ha,
    model_version,
    model_backend,
    run_id
  )
  VALUES (
    p_planting_id,
    p_predicted_t_ha,
    COALESCE(p_model_version, 'baseline-cpu-v1'),
    p_model_backend,
    COALESCE(p_run_id, gen_random_uuid())
  )
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION crop_yield.sp_enqueue_season_backlog(
  p_season_id integer DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_yield, crop_core, crop_wf, pg_temp
AS $$
DECLARE
  v_season record;
  v_count integer := 0;
BEGIN
  FOR v_season IN
    SELECT s.id AS season_id
    FROM crop_core.seasons s
    WHERE p_season_id IS NULL OR s.id = p_season_id
  LOOP
    PERFORM crop_wf.sp_enqueue_processing_task(
      'crop.yield.predict',
      jsonb_build_object('season_id', v_season.season_id, 'reason', 'weekly_backlog'),
      'crop.model',
      'yield_weekly_backlog',
      'yield:season:' || v_season.season_id::text || ':' || gen_random_uuid()::text
    );
    v_count := v_count + 1;
  END LOOP;
  RETURN v_count;
END;
$$;
