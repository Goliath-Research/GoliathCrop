-- GoliathCrop Phase 1 — crop_trial schema
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_trial;

CREATE TABLE IF NOT EXISTS crop_trial.trials (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_id integer NOT NULL REFERENCES crop_core.seasons (id) ON DELETE CASCADE,
  name text NOT NULL,
  design text,
  UNIQUE (season_id, name)
);

ALTER TABLE crop_core.plots
  DROP CONSTRAINT IF EXISTS plots_trial_fk;
ALTER TABLE crop_core.plots
  ADD CONSTRAINT plots_trial_fk
  FOREIGN KEY (trial_id) REFERENCES crop_trial.trials (id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS crop_trial.treatments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trial_id integer NOT NULL REFERENCES crop_trial.trials (id) ON DELETE CASCADE,
  code text NOT NULL,
  description text,
  UNIQUE (trial_id, code)
);

CREATE TABLE IF NOT EXISTS crop_trial.replicates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treatment_id integer NOT NULL REFERENCES crop_trial.treatments (id) ON DELETE CASCADE,
  replicate_number integer NOT NULL,
  plot_id integer REFERENCES crop_core.plots (id) ON DELETE SET NULL,
  UNIQUE (treatment_id, replicate_number)
);

CREATE TABLE IF NOT EXISTS crop_trial.plot_measurements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plot_id integer NOT NULL REFERENCES crop_core.plots (id) ON DELETE CASCADE,
  metric text NOT NULL,
  value double precision,
  measured_on date NOT NULL DEFAULT CURRENT_DATE
);

CREATE OR REPLACE VIEW crop_trial.v_trial AS
SELECT
  t.id,
  t.season_id,
  t.name,
  t.design,
  COALESCE(tr.cnt, 0)::integer AS treatment_count,
  COALESCE(rp.cnt, 0)::integer AS replicate_count
FROM crop_trial.trials t
LEFT JOIN LATERAL (
  SELECT count(*) AS cnt FROM crop_trial.treatments tx WHERE tx.trial_id = t.id
) tr ON true
LEFT JOIN LATERAL (
  SELECT count(*) AS cnt
  FROM crop_trial.replicates rx
  INNER JOIN crop_trial.treatments tx ON tx.id = rx.treatment_id
  WHERE tx.trial_id = t.id
) rp ON true;

ALTER TABLE crop_trial.trials ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS trials_season_access ON crop_trial.trials;
CREATE POLICY trials_season_access ON crop_trial.trials
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM crop_core.seasons s
      WHERE s.id = season_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          s.farm_id
        )
    )
  );

ALTER TABLE crop_trial.treatments ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS treatments_trial_access ON crop_trial.treatments;
CREATE POLICY treatments_trial_access ON crop_trial.treatments
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_trial.trials t
      INNER JOIN crop_core.seasons s ON s.id = t.season_id
      WHERE t.id = trial_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          s.farm_id
        )
    )
  );

ALTER TABLE crop_trial.replicates ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS replicates_treatment_access ON crop_trial.replicates;
CREATE POLICY replicates_treatment_access ON crop_trial.replicates
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_trial.treatments tx
      INNER JOIN crop_trial.trials t ON t.id = tx.trial_id
      INNER JOIN crop_core.seasons s ON s.id = t.season_id
      WHERE tx.id = treatment_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          s.farm_id
        )
    )
  );

ALTER TABLE crop_trial.plot_measurements ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS plot_measurements_plot_access ON crop_trial.plot_measurements;
CREATE POLICY plot_measurements_plot_access ON crop_trial.plot_measurements
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_core.plots p
      INNER JOIN crop_core.fields fld ON fld.id = p.field_id
      WHERE p.id = plot_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

CREATE OR REPLACE FUNCTION crop_trial.fn_trial_results(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  plot_id integer,
  plot_code text,
  treatment_code text,
  replicate_number integer,
  metric text,
  value double precision,
  measured_on date
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_trial, crop_core, portal, pg_temp
AS $$
DECLARE
  v_trial_id integer;
  v_lim integer;
  v_farm_id integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_trial_id := (p_params->>'trial_id')::integer;
  IF v_trial_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'trial_id is required');
  END IF;
  SELECT s.farm_id INTO v_farm_id
  FROM crop_trial.trials t
  INNER JOIN crop_core.seasons s ON s.id = t.season_id
  WHERE t.id = v_trial_id;
  IF v_farm_id IS NULL OR NOT crop_core.fn_user_can_access_farm(p_user_id, v_farm_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'trial scope denied');
  END IF;
  v_lim := GREATEST(0, COALESCE(p_limit, 2000));
  RETURN QUERY
  SELECT
    p.id,
    p.code,
    tr.treatment_code,
    tr.replicate_number,
    pm.metric,
    pm.value,
    pm.measured_on
  FROM crop_trial.plot_measurements pm
  INNER JOIN crop_core.plots p ON p.id = pm.plot_id
  LEFT JOIN LATERAL (
    SELECT tx.code AS treatment_code, rx.replicate_number
    FROM crop_trial.replicates rx
    INNER JOIN crop_trial.treatments tx ON tx.id = rx.treatment_id
    WHERE rx.plot_id = p.id
      AND tx.trial_id = v_trial_id
    ORDER BY rx.replicate_number
    LIMIT 1
  ) tr ON true
  WHERE p.trial_id = v_trial_id
  ORDER BY p.code, pm.metric, pm.measured_on
  LIMIT v_lim;
END;
$$;
