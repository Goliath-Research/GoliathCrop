-- GoliathCrop Phase 1 — crop_ops schema
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_ops;

CREATE TABLE IF NOT EXISTS crop_ops.equipment (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  name text NOT NULL,
  kind text,
  UNIQUE (farm_id, name)
);

CREATE TABLE IF NOT EXISTS crop_ops.inventory_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  name text NOT NULL,
  category text,
  unit text NOT NULL DEFAULT 'kg',
  UNIQUE (farm_id, name)
);

CREATE TABLE IF NOT EXISTS crop_ops.inventory_lots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id integer NOT NULL REFERENCES crop_ops.inventory_items (id) ON DELETE CASCADE,
  lot text NOT NULL,
  on_hand double precision NOT NULL DEFAULT 0,
  UNIQUE (item_id, lot)
);

CREATE TABLE IF NOT EXISTS crop_ops.operations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planting_id integer NOT NULL REFERENCES crop_core.plantings (id) ON DELETE CASCADE,
  kind text NOT NULL,
  performed_on timestamptz NOT NULL,
  rate double precision,
  rate_unit text,
  equipment text,
  operator text,
  notes text
);

CREATE INDEX IF NOT EXISTS operations_planting_performed_idx
  ON crop_ops.operations (planting_id, performed_on DESC);

CREATE TABLE IF NOT EXISTS crop_ops.operation_inputs (
  operation_id integer NOT NULL REFERENCES crop_ops.operations (id) ON DELETE CASCADE,
  lot_id integer NOT NULL REFERENCES crop_ops.inventory_lots (id),
  quantity double precision NOT NULL,
  PRIMARY KEY (operation_id, lot_id)
);

CREATE OR REPLACE VIEW crop_ops.v_operation AS
SELECT
  o.id,
  o.planting_id,
  o.kind,
  o.performed_on,
  o.rate,
  o.rate_unit,
  o.equipment,
  o.operator
FROM crop_ops.operations o;

CREATE OR REPLACE VIEW crop_ops.v_input_lot AS
SELECT
  l.id,
  l.item_id,
  i.name AS item_name,
  l.lot,
  l.on_hand,
  i.unit
FROM crop_ops.inventory_lots l
JOIN crop_ops.inventory_items i ON i.id = l.item_id;

ALTER TABLE crop_ops.operations ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_ops.inventory_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_ops.inventory_lots ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS operations_planting_access ON crop_ops.operations;
CREATE POLICY operations_planting_access ON crop_ops.operations
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_core.plantings pl
      JOIN crop_core.fields fld ON fld.id = pl.field_id
      WHERE pl.id = planting_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

DROP POLICY IF EXISTS inventory_items_farm ON crop_ops.inventory_items;
CREATE POLICY inventory_items_farm ON crop_ops.inventory_items
  FOR ALL
  USING (
    crop_core.fn_user_can_access_farm(
      NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
      farm_id
    )
  );

DROP POLICY IF EXISTS inventory_lots_item ON crop_ops.inventory_lots;
CREATE POLICY inventory_lots_item ON crop_ops.inventory_lots
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM crop_ops.inventory_items i
      WHERE i.id = item_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          i.farm_id
        )
    )
  );

CREATE OR REPLACE FUNCTION crop_ops.fn_semantic_operation_list(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  operation_id integer,
  planting_id integer,
  kind text,
  performed_on timestamptz,
  rate double precision,
  rate_unit text,
  equipment text,
  operator text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_ops, crop_core, portal, pg_temp
AS $$
DECLARE
  v_planting_id integer;
  v_kind text;
  v_from timestamptz;
  v_to timestamptz;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_planting_id := NULLIF(p_params->>'planting_id', '')::integer;
  v_kind := NULLIF(p_params->>'kind', '');
  v_from := NULLIF(p_params->>'from', '')::timestamptz;
  v_to := NULLIF(p_params->>'to', '')::timestamptz;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    o.id,
    o.planting_id,
    o.kind,
    o.performed_on,
    o.rate,
    o.rate_unit,
    o.equipment,
    o.operator
  FROM crop_ops.v_operation o
  INNER JOIN crop_core.plantings pl ON pl.id = o.planting_id
  INNER JOIN crop_core.fields fld ON fld.id = pl.field_id
  WHERE crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
    AND (v_planting_id IS NULL OR o.planting_id = v_planting_id)
    AND (v_kind IS NULL OR o.kind = v_kind)
    AND (v_from IS NULL OR o.performed_on >= v_from)
    AND (v_to IS NULL OR o.performed_on <= v_to)
  ORDER BY o.performed_on DESC
  LIMIT v_lim;
END;
$$;
