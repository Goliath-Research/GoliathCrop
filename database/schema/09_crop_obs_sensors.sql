-- GoliathCrop Phase 3 — sensor devices and TimescaleDB readings hypertable
SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS crop_obs.devices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  field_id integer REFERENCES crop_core.fields (id) ON DELETE SET NULL,
  external_id text,
  kind text NOT NULL DEFAULT 'soil_moisture',
  label text,
  last_reading_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT devices_farm_external_uniq UNIQUE (farm_id, external_id)
);

CREATE INDEX IF NOT EXISTS devices_farm_idx ON crop_obs.devices (farm_id);

CREATE OR REPLACE VIEW crop_obs.v_device AS
SELECT
  d.id AS device_id,
  d.farm_id,
  d.kind,
  d.field_id,
  d.label,
  d.external_id,
  d.last_reading_at
FROM crop_obs.devices d;

CREATE TABLE IF NOT EXISTS crop_obs.sensor_readings (
  ts timestamptz NOT NULL,
  device_id integer NOT NULL REFERENCES crop_obs.devices (id) ON DELETE CASCADE,
  metric text NOT NULL,
  value double precision NOT NULL,
  quality text,
  PRIMARY KEY (device_id, ts, metric)
);

CREATE INDEX IF NOT EXISTS sensor_readings_device_ts_idx
  ON crop_obs.sensor_readings (device_id, ts DESC);

DO $crop_hypertable$
BEGIN
  IF to_regprocedure('timescaledb.create_hypertable(regclass,name,chunk_time_interval=>anyelement,if_not_exists=>boolean)') IS NOT NULL
     OR to_regprocedure('create_hypertable(regclass,name,if_not_exists=>boolean)') IS NOT NULL THEN
    PERFORM create_hypertable(
      'crop_obs.sensor_readings',
      'ts',
      if_not_exists => TRUE
    );
  END IF;
EXCEPTION
  WHEN OTHERS THEN
    RAISE NOTICE 'sensor_readings hypertable skipped: %', SQLERRM;
END $crop_hypertable$;

ALTER TABLE crop_obs.devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_obs.sensor_readings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS devices_farm_access ON crop_obs.devices;
CREATE POLICY devices_farm_access ON crop_obs.devices
  FOR ALL
  USING (
    crop_core.fn_user_can_access_farm(
      NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
      farm_id
    )
  );

DROP POLICY IF EXISTS sensor_readings_device_access ON crop_obs.sensor_readings;
CREATE POLICY sensor_readings_device_access ON crop_obs.sensor_readings
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_obs.devices d
      WHERE d.id = device_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          d.farm_id
        )
    )
  );

CREATE OR REPLACE FUNCTION crop_obs.fn_timescale_available()
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'timescaledb');
$$;

CREATE OR REPLACE FUNCTION crop_obs.fn_readings_window(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  device_id integer,
  ts timestamptz,
  metric text,
  value double precision,
  bucket timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_obs, crop_core, portal, pg_temp
AS $$
DECLARE
  v_device_id integer;
  v_from timestamptz;
  v_to timestamptz;
  v_bucket text;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_device_id := (p_params->>'sensor_id')::integer;
  IF v_device_id IS NULL THEN
    v_device_id := (p_params->>'device_id')::integer;
  END IF;
  IF v_device_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'sensor_id is required');
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM crop_obs.devices d
    WHERE d.id = v_device_id
      AND crop_core.fn_user_can_access_farm(p_user_id, d.farm_id)
  ) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'sensor scope denied');
  END IF;
  v_from := NULLIF(p_params->>'from', '')::timestamptz;
  v_to := NULLIF(p_params->>'to', '')::timestamptz;
  v_bucket := COALESCE(NULLIF(p_params->>'bucket', ''), '1 hour');
  v_lim := GREATEST(0, COALESCE(p_limit, 5000));

  IF crop_obs.fn_timescale_available() THEN
    RETURN QUERY EXECUTE format(
      $q$
      SELECT
        r.device_id,
        r.ts,
        r.metric,
        r.value,
        time_bucket(%L::interval, r.ts) AS bucket
      FROM crop_obs.sensor_readings r
      WHERE r.device_id = $1
        AND ($2 IS NULL OR r.ts >= $2)
        AND ($3 IS NULL OR r.ts <= $3)
      ORDER BY r.ts DESC
      LIMIT $4
      $q$,
      v_bucket
    )
    USING v_device_id, v_from, v_to, v_lim;
  ELSE
    RETURN QUERY
    SELECT
      r.device_id,
      r.ts,
      r.metric,
      r.value,
      date_trunc('hour', r.ts) AS bucket
    FROM crop_obs.sensor_readings r
    WHERE r.device_id = v_device_id
      AND (v_from IS NULL OR r.ts >= v_from)
      AND (v_to IS NULL OR r.ts <= v_to)
    ORDER BY r.ts DESC
    LIMIT v_lim;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION crop_obs.fn_semantic_device_list(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  device_id integer,
  farm_id integer,
  kind text,
  field_id integer,
  label text,
  last_reading_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_obs, crop_core, portal, pg_temp
AS $$
DECLARE
  v_farm_id integer;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_farm_id := (p_params->>'farm_id')::integer;
  IF v_farm_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'farm_id is required');
  END IF;
  IF NOT crop_core.fn_user_can_access_farm(p_user_id, v_farm_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'farm scope denied');
  END IF;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    d.device_id,
    d.farm_id,
    d.kind,
    d.field_id,
    d.label,
    d.last_reading_at
  FROM crop_obs.v_device d
  WHERE d.farm_id = v_farm_id
  ORDER BY d.kind, d.device_id
  LIMIT v_lim;
END;
$$;

CREATE OR REPLACE FUNCTION crop_obs.sp_ingest_sensor_batch(
  p_device_id integer,
  p_readings jsonb
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_obs, crop_wf, pg_temp
AS $$
DECLARE
  v_row jsonb;
  v_inserted integer := 0;
  v_last timestamptz;
BEGIN
  IF p_device_id IS NULL THEN
    RAISE EXCEPTION 'device_id is required';
  END IF;
  IF p_readings IS NULL OR jsonb_typeof(p_readings) <> 'array' THEN
    RAISE EXCEPTION 'readings must be a JSON array';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM crop_obs.devices d WHERE d.id = p_device_id) THEN
    RAISE EXCEPTION 'unknown device_id %', p_device_id;
  END IF;

  FOR v_row IN SELECT value FROM jsonb_array_elements(p_readings)
  LOOP
    INSERT INTO crop_obs.sensor_readings (ts, device_id, metric, value, quality)
    VALUES (
      (v_row->>'ts')::timestamptz,
      p_device_id,
      v_row->>'metric',
      (v_row->>'value')::double precision,
      v_row->>'quality'
    )
    ON CONFLICT (device_id, ts, metric) DO UPDATE SET
      value = EXCLUDED.value,
      quality = EXCLUDED.quality;
    v_inserted := v_inserted + 1;
    IF v_last IS NULL OR (v_row->>'ts')::timestamptz > v_last THEN
      v_last := (v_row->>'ts')::timestamptz;
    END IF;
  END LOOP;

  IF v_last IS NOT NULL THEN
    UPDATE crop_obs.devices
    SET last_reading_at = GREATEST(COALESCE(last_reading_at, v_last), v_last)
    WHERE id = p_device_id;
  END IF;

  PERFORM crop_wf.sp_enqueue_processing_task(
    'crop.sensor.qc',
    jsonb_build_object('device_id', p_device_id, 'reading_count', v_inserted),
    'crop.ingest',
    'sensor_batch_ingested',
    'sensor:' || p_device_id::text || ':' || gen_random_uuid()::text
  );

  RETURN v_inserted;
END;
$$;
