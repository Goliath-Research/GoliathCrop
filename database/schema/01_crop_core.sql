-- GoliathCrop Phase 1 — crop_core schema (farms, fields, seasons, plantings)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_core;

CREATE TABLE IF NOT EXISTS crop_core.farms (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  name text NOT NULL,
  location text,
  timezone text DEFAULT 'UTC',
  units text DEFAULT 'metric',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT farms_organization_fk
    FOREIGN KEY (organization_id) REFERENCES portal."Organizations" ("ID")
);

CREATE TABLE IF NOT EXISTS crop_core.farm_members (
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  user_id integer NOT NULL,
  member_role text NOT NULL DEFAULT 'member',
  PRIMARY KEY (farm_id, user_id)
);

CREATE TABLE IF NOT EXISTS crop_core.crops (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  common_name text NOT NULL
);

CREATE TABLE IF NOT EXISTS crop_core.varieties (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crop_id integer NOT NULL REFERENCES crop_core.crops (id),
  species text,
  variety text NOT NULL,
  maturity_days integer,
  gdd_base_c double precision
);

CREATE TABLE IF NOT EXISTS crop_core.seasons (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  year integer NOT NULL,
  campaign text,
  status text DEFAULT 'planned'
);

ALTER TABLE crop_core.seasons DROP CONSTRAINT IF EXISTS seasons_farm_id_year_campaign_key;

CREATE UNIQUE INDEX IF NOT EXISTS seasons_farm_year_campaign_idx
  ON crop_core.seasons (farm_id, year, COALESCE(campaign, ''));

CREATE TABLE IF NOT EXISTS crop_core.fields (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  name text NOT NULL,
  area_ha double precision,
  soil_type text,
  geom geometry(MultiPolygon, 4326),
  UNIQUE (farm_id, name)
);

CREATE INDEX IF NOT EXISTS fields_geom_gix ON crop_core.fields USING GIST (geom);

CREATE TABLE IF NOT EXISTS crop_core.plots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id integer NOT NULL REFERENCES crop_core.fields (id) ON DELETE CASCADE,
  trial_id integer,
  code text NOT NULL,
  geom geometry(MultiPolygon, 4326),
  UNIQUE (field_id, code)
);

CREATE TABLE IF NOT EXISTS crop_core.plantings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id integer NOT NULL REFERENCES crop_core.fields (id) ON DELETE CASCADE,
  season_id integer NOT NULL REFERENCES crop_core.seasons (id) ON DELETE CASCADE,
  variety_id integer NOT NULL REFERENCES crop_core.varieties (id),
  sown_on date,
  density double precision,
  seed_lot text
);

CREATE OR REPLACE FUNCTION crop_core.fn_user_can_access_farm(p_user_id integer, p_farm_id integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = crop_core, portal, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM crop_core.farms f
    WHERE f.id = p_farm_id
      AND (
        f.organization_id = ANY (portal.fn_semantic_user_organization_ids(p_user_id))
        OR EXISTS (
          SELECT 1 FROM crop_core.farm_members m
          WHERE m.farm_id = f.id AND m.user_id = p_user_id
        )
      )
  );
$$;

CREATE OR REPLACE VIEW crop_core.v_farm AS
SELECT
  f.id,
  f.organization_id,
  f.name,
  f.location,
  f.timezone,
  f.units
FROM crop_core.farms f;

CREATE OR REPLACE VIEW crop_core.v_field AS
SELECT
  fld.id,
  fld.farm_id,
  fld.name,
  fld.area_ha,
  fld.soil_type,
  CASE
    WHEN fld.geom IS NULL THEN NULL
    ELSE ST_AsGeoJSON(fld.geom)::text
  END AS geometry
FROM crop_core.fields fld;

CREATE OR REPLACE VIEW crop_core.v_plot AS
SELECT
  p.id,
  p.field_id,
  p.trial_id,
  p.code,
  CASE
    WHEN p.geom IS NULL THEN NULL
    ELSE ST_AsGeoJSON(p.geom)::text
  END AS geometry
FROM crop_core.plots p;

CREATE OR REPLACE VIEW crop_core.v_season AS
SELECT
  s.id,
  s.farm_id,
  s.year,
  s.campaign,
  s.status
FROM crop_core.seasons s;

CREATE OR REPLACE VIEW crop_core.v_planting AS
SELECT
  pl.id,
  pl.field_id,
  pl.season_id,
  pl.variety_id,
  pl.sown_on,
  pl.density,
  pl.seed_lot
FROM crop_core.plantings pl;

CREATE OR REPLACE VIEW crop_core.v_variety AS
SELECT
  v.id,
  v.crop_id,
  v.species,
  v.variety,
  v.maturity_days,
  v.gdd_base_c
FROM crop_core.varieties v;

