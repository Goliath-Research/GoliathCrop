CREATE OR REPLACE FUNCTION crop_core.fn_semantic_field_list_by_farm(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  field_id integer,
  farm_id integer,
  name text,
  area_ha double precision,
  soil_type text,
  geometry text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_core, portal, pg_temp
AS $$
DECLARE
  v_farm_id integer;
  v_season_id integer;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_farm_id := (p_params->>'farm_id')::integer;
  IF v_farm_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'farm_id is required');
  END IF;
  IF NOT crop_core.fn_user_can_access_farm(p_user_id, v_farm_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'farm scope denied');
  END IF;
  v_season_id := NULLIF(p_params->>'season_id', '')::integer;
  IF v_season_id IS NOT NULL THEN
    IF NOT EXISTS (
      SELECT 1 FROM crop_core.seasons s
      WHERE s.id = v_season_id AND s.farm_id = v_farm_id
    ) THEN
      PERFORM portal.fn_semantic_raise('GS403', 'season scope denied');
    END IF;
  END IF;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    v.id,
    v.farm_id,
    v.name,
    v.area_ha,
    v.soil_type,
    v.geometry
  FROM crop_core.v_field v
  WHERE v.farm_id = v_farm_id
    AND (
      v_season_id IS NULL
      OR EXISTS (
        SELECT 1 FROM crop_core.plantings pl
        WHERE pl.field_id = v.id AND pl.season_id = v_season_id
      )
    )
  ORDER BY v.name
  LIMIT v_lim;
END;
$$;

CREATE OR REPLACE FUNCTION crop_core.fn_semantic_planting_list_by_season(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  planting_id integer,
  field_id integer,
  season_id integer,
  variety_id integer,
  sown_on date,
  density double precision,
  seed_lot text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_core, portal, pg_temp
AS $$
DECLARE
  v_season_id integer;
  v_field_id integer;
  v_lim integer;
  v_farm_id integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_season_id := (p_params->>'season_id')::integer;
  IF v_season_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'season_id is required');
  END IF;
  SELECT s.farm_id INTO v_farm_id FROM crop_core.seasons s WHERE s.id = v_season_id;
  IF v_farm_id IS NULL OR NOT crop_core.fn_user_can_access_farm(p_user_id, v_farm_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'season scope denied');
  END IF;
  v_field_id := NULLIF(p_params->>'field_id', '')::integer;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    pl.id,
    pl.field_id,
    pl.season_id,
    pl.variety_id,
    pl.sown_on,
    pl.density,
    pl.seed_lot
  FROM crop_core.v_planting pl
  WHERE pl.season_id = v_season_id
    AND (v_field_id IS NULL OR pl.field_id = v_field_id)
  ORDER BY pl.field_id, pl.id
  LIMIT v_lim;
END;
$$;
