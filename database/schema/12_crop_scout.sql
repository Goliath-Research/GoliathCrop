-- GoliathCrop Phase 4 — scouting observations (map pins, photos, severity)
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_scout;

CREATE TABLE IF NOT EXISTS crop_scout.pest_catalog (
  code text PRIMARY KEY,
  display_name text NOT NULL,
  category text NOT NULL DEFAULT 'pest'
);

INSERT INTO crop_scout.pest_catalog (code, display_name, category)
VALUES
  ('aphids', 'Aphids', 'pest'),
  ('rust', 'Leaf rust', 'disease'),
  ('weed_pressure', 'Weed pressure', 'weed'),
  ('other', 'Other / unspecified', 'other')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE IF NOT EXISTS crop_scout.observations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id integer NOT NULL REFERENCES crop_core.fields (id) ON DELETE CASCADE,
  observed_at timestamptz NOT NULL DEFAULT now(),
  pest_code text NOT NULL REFERENCES crop_scout.pest_catalog (code),
  severity smallint NOT NULL DEFAULT 2,
  notes text,
  geom geometry(Point, 4326),
  created_by integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT observations_severity_chk CHECK (severity BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS observations_field_observed_idx
  ON crop_scout.observations (field_id, observed_at DESC);

CREATE TABLE IF NOT EXISTS crop_scout.photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  observation_id bigint NOT NULL REFERENCES crop_scout.observations (id) ON DELETE CASCADE,
  storage_uri text NOT NULL,
  caption text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE VIEW crop_scout.v_observation AS
SELECT
  o.id AS observation_id,
  o.field_id,
  o.observed_at,
  o.pest_code AS pest,
  pc.display_name AS pest_name,
  o.severity,
  o.notes,
  CASE WHEN o.geom IS NOT NULL THEN ST_AsGeoJSON(o.geom)::text ELSE NULL END AS geo_json,
  (
    SELECT p.storage_uri
    FROM crop_scout.photos p
    WHERE p.observation_id = o.id
    ORDER BY p.id
    LIMIT 1
  ) AS photo_uri
FROM crop_scout.observations o
INNER JOIN crop_scout.pest_catalog pc ON pc.code = o.pest_code;

ALTER TABLE crop_scout.observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_scout.photos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS observations_field_access ON crop_scout.observations;
CREATE POLICY observations_field_access ON crop_scout.observations
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_core.fields fld
      WHERE fld.id = field_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

DROP POLICY IF EXISTS photos_observation_access ON crop_scout.photos;
CREATE POLICY photos_observation_access ON crop_scout.photos
  FOR ALL
  USING (
    EXISTS (
      SELECT 1
      FROM crop_scout.observations o
      INNER JOIN crop_core.fields fld ON fld.id = o.field_id
      WHERE o.id = observation_id
        AND crop_core.fn_user_can_access_farm(
          NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
          fld.farm_id
        )
    )
  );

CREATE OR REPLACE FUNCTION crop_scout.fn_semantic_list_by_field(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  observation_id bigint,
  field_id integer,
  observed_at timestamptz,
  pest text,
  pest_name text,
  severity smallint,
  notes text,
  geo_json text,
  photo_uri text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_scout, crop_core, portal, pg_temp
AS $$
DECLARE
  v_field_id integer;
  v_from timestamptz;
  v_to timestamptz;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_field_id := (p_params->>'field_id')::integer;
  IF v_field_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'field_id is required');
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.fields fld
    WHERE fld.id = v_field_id
      AND crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
  ) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'field scope denied');
  END IF;
  v_from := NULLIF(p_params->>'from', '')::timestamptz;
  v_to := NULLIF(p_params->>'to', '')::timestamptz;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    v.observation_id,
    v.field_id,
    v.observed_at,
    v.pest,
    v.pest_name,
    v.severity,
    v.notes,
    v.geo_json,
    v.photo_uri
  FROM crop_scout.v_observation v
  WHERE v.field_id = v_field_id
    AND (v_from IS NULL OR v.observed_at >= v_from)
    AND (v_to IS NULL OR v.observed_at <= v_to)
  ORDER BY v.observed_at DESC
  LIMIT v_lim;
END;
$$;

CREATE OR REPLACE FUNCTION crop_scout.sp_record_observation(
  p_user_id integer,
  p_field_id integer,
  p_observed_at timestamptz,
  p_pest_code text,
  p_severity smallint,
  p_notes text DEFAULT NULL,
  p_geo_json text DEFAULT NULL,
  p_photo_uri text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_scout, crop_core, portal, pg_temp
AS $$
DECLARE
  v_farm_id integer;
  v_observation_id bigint;
  v_geom geometry;
BEGIN
  IF p_user_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS401', 'user required');
  END IF;
  SELECT fld.farm_id INTO v_farm_id
  FROM crop_core.fields fld
  WHERE fld.id = p_field_id;
  IF v_farm_id IS NULL OR NOT crop_core.fn_user_can_access_farm(p_user_id, v_farm_id) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'field scope denied');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM crop_scout.pest_catalog pc WHERE pc.code = p_pest_code) THEN
    PERFORM portal.fn_semantic_raise('GS501', 'unknown pest code');
  END IF;
  IF p_severity IS NULL OR p_severity < 1 OR p_severity > 5 THEN
    PERFORM portal.fn_semantic_raise('GS501', 'severity must be 1-5');
  END IF;
  IF p_geo_json IS NOT NULL AND btrim(p_geo_json) <> '' THEN
    v_geom := ST_SetSRID(ST_GeomFromGeoJSON(p_geo_json), 4326);
  END IF;
  PERFORM set_config('goliath.crop.user_id', p_user_id::text, true);
  INSERT INTO crop_scout.observations (
    field_id,
    observed_at,
    pest_code,
    severity,
    notes,
    geom,
    created_by
  )
  VALUES (
    p_field_id,
    COALESCE(p_observed_at, now()),
    p_pest_code,
    p_severity,
    p_notes,
    v_geom,
    p_user_id
  )
  RETURNING id INTO v_observation_id;

  IF p_photo_uri IS NOT NULL AND btrim(p_photo_uri) <> '' THEN
    INSERT INTO crop_scout.photos (observation_id, storage_uri)
    VALUES (v_observation_id, p_photo_uri);
  END IF;

  RETURN v_observation_id;
END;
$$;
