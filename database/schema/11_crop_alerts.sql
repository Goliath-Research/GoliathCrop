-- GoliathCrop Phase 3 — frost, stress, and pest threshold alerts
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_alerts;

CREATE TABLE IF NOT EXISTS crop_alerts.threshold_rules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  kind text NOT NULL,
  metric text NOT NULL,
  threshold_value double precision NOT NULL,
  comparison text NOT NULL DEFAULT 'lt',
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT threshold_rules_kind_chk
    CHECK (kind IN ('frost', 'stress', 'pest')),
  CONSTRAINT threshold_rules_comparison_chk
    CHECK (comparison IN ('lt', 'lte', 'gt', 'gte'))
);

CREATE TABLE IF NOT EXISTS crop_alerts.alert_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_id integer NOT NULL REFERENCES crop_core.farms (id) ON DELETE CASCADE,
  field_id integer REFERENCES crop_core.fields (id) ON DELETE SET NULL,
  device_id integer REFERENCES crop_obs.devices (id) ON DELETE SET NULL,
  kind text NOT NULL,
  severity text NOT NULL DEFAULT 'warning',
  message text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb,
  opened_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  CONSTRAINT alert_events_kind_chk
    CHECK (kind IN ('frost', 'stress', 'pest'))
);

CREATE INDEX IF NOT EXISTS alert_events_open_idx
  ON crop_alerts.alert_events (farm_id, opened_at DESC)
  WHERE resolved_at IS NULL;

ALTER TABLE crop_alerts.threshold_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_alerts.alert_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS threshold_rules_farm_access ON crop_alerts.threshold_rules;
CREATE POLICY threshold_rules_farm_access ON crop_alerts.threshold_rules
  FOR ALL
  USING (
    crop_core.fn_user_can_access_farm(
      NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
      farm_id
    )
  );

DROP POLICY IF EXISTS alert_events_farm_access ON crop_alerts.alert_events;
CREATE POLICY alert_events_farm_access ON crop_alerts.alert_events
  FOR ALL
  USING (
    crop_core.fn_user_can_access_farm(
      NULLIF(current_setting('goliath.crop.user_id', true), '')::integer,
      farm_id
    )
  );

CREATE OR REPLACE FUNCTION crop_alerts.sp_open_alert(
  p_farm_id integer,
  p_field_id integer,
  p_kind text,
  p_message text,
  p_detail jsonb DEFAULT '{}'::jsonb,
  p_device_id integer DEFAULT NULL,
  p_severity text DEFAULT 'warning'
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_alerts, crop_wf, pg_temp
AS $$
DECLARE
  v_id bigint;
BEGIN
  INSERT INTO crop_alerts.alert_events (
    farm_id,
    field_id,
    device_id,
    kind,
    severity,
    message,
    detail
  )
  VALUES (
    p_farm_id,
    p_field_id,
    p_device_id,
    p_kind,
    COALESCE(p_severity, 'warning'),
    p_message,
    COALESCE(p_detail, '{}'::jsonb)
  )
  RETURNING id INTO v_id;

  PERFORM crop_wf.sp_enqueue_processing_task(
    'crop.alert.evaluate',
    jsonb_build_object('alert_id', v_id, 'farm_id', p_farm_id, 'kind', p_kind),
    'crop.alerts',
    'alert_opened',
    'alert:' || v_id::text
  );

  RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION crop_alerts.sp_evaluate_frost_for_field(
  p_field_id integer,
  p_obs_date date,
  p_tmin_c double precision,
  p_frost_threshold_c double precision DEFAULT 0.0
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_alerts, crop_core, pg_temp
AS $$
DECLARE
  v_farm_id integer;
  v_alert_id bigint;
BEGIN
  SELECT fld.farm_id INTO v_farm_id
  FROM crop_core.fields fld
  WHERE fld.id = p_field_id;

  IF v_farm_id IS NULL OR p_tmin_c IS NULL THEN
    RETURN NULL;
  END IF;

  IF p_tmin_c > p_frost_threshold_c THEN
    RETURN NULL;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM crop_alerts.alert_events e
    WHERE e.field_id = p_field_id
      AND e.kind = 'frost'
      AND (e.detail->>'obs_date')::date = p_obs_date
      AND e.resolved_at IS NULL
  ) THEN
    RETURN NULL;
  END IF;

  v_alert_id := crop_alerts.sp_open_alert(
    v_farm_id,
    p_field_id,
    'frost',
    format('Frost risk: tmin %.1f°C on %s', p_tmin_c, p_obs_date),
    jsonb_build_object(
      'obs_date', p_obs_date,
      'tmin_c', p_tmin_c,
      'threshold_c', p_frost_threshold_c
    ),
    NULL,
    'critical'
  );
  RETURN v_alert_id;
END;
$$;

CREATE OR REPLACE FUNCTION crop_alerts.sp_evaluate_sensor_thresholds(
  p_device_id integer
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_alerts, crop_obs, pg_temp
AS $$
DECLARE
  v_device crop_obs.devices%ROWTYPE;
  v_rule crop_alerts.threshold_rules%ROWTYPE;
  v_reading record;
  v_opened integer := 0;
  v_breached boolean;
BEGIN
  SELECT * INTO v_device FROM crop_obs.devices d WHERE d.id = p_device_id;
  IF NOT FOUND THEN
    RETURN 0;
  END IF;

  FOR v_rule IN
    SELECT *
    FROM crop_alerts.threshold_rules r
    WHERE r.farm_id = v_device.farm_id
      AND r.active
      AND r.kind IN ('stress', 'pest')
  LOOP
    SELECT r.metric, r.value, r.ts
    INTO v_reading
    FROM crop_obs.sensor_readings r
    WHERE r.device_id = p_device_id
      AND r.metric = v_rule.metric
    ORDER BY r.ts DESC
    LIMIT 1;

    IF v_reading.value IS NULL THEN
      CONTINUE;
    END IF;

    v_breached := CASE v_rule.comparison
      WHEN 'lt' THEN v_reading.value < v_rule.threshold_value
      WHEN 'lte' THEN v_reading.value <= v_rule.threshold_value
      WHEN 'gt' THEN v_reading.value > v_rule.threshold_value
      WHEN 'gte' THEN v_reading.value >= v_rule.threshold_value
      ELSE false
    END;

    IF NOT v_breached THEN
      CONTINUE;
    END IF;

    IF EXISTS (
      SELECT 1
      FROM crop_alerts.alert_events e
      WHERE e.device_id = p_device_id
        AND e.kind = v_rule.kind
        AND e.resolved_at IS NULL
        AND e.detail->>'metric' = v_rule.metric
    ) THEN
      CONTINUE;
    END IF;

    PERFORM crop_alerts.sp_open_alert(
      v_device.farm_id,
      v_device.field_id,
      v_rule.kind,
      format(
        '%s threshold breached for metric %s (value %s)',
        v_rule.kind,
        v_rule.metric,
        v_reading.value
      ),
      jsonb_build_object(
        'device_id', p_device_id,
        'metric', v_rule.metric,
        'value', v_reading.value,
        'threshold', v_rule.threshold_value,
        'comparison', v_rule.comparison,
        'ts', v_reading.ts
      ),
      p_device_id,
      'warning'
    );
    v_opened := v_opened + 1;
  END LOOP;

  RETURN v_opened;
END;
$$;
