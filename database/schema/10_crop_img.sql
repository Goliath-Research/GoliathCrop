CREATE OR REPLACE FUNCTION crop_img.sp_complete_scene_index(
  p_scene_id bigint,
  p_storage_uri text,
  p_ndvi_mean double precision,
  p_ndvi_min double precision DEFAULT NULL,
  p_ndvi_max double precision DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_img, pg_temp
AS $$
DECLARE
  v_field_id integer;
  v_asset_id bigint;
BEGIN
  SELECT s.field_id, s.raster_asset_id
  INTO v_field_id, v_asset_id
  FROM crop_img.imagery_scenes s
  WHERE s.id = p_scene_id
  FOR UPDATE;

  IF v_field_id IS NULL THEN
    RAISE EXCEPTION 'unknown scene_id %', p_scene_id;
  END IF;

  IF v_asset_id IS NULL THEN
    INSERT INTO crop_img.raster_assets (
      field_id,
      storage_uri,
      source,
      acquired_at,
      status
    )
    SELECT
      s.field_id,
      p_storage_uri,
      s.source,
      s.acquired_at,
      'ready'
    FROM crop_img.imagery_scenes s
    WHERE s.id = p_scene_id
    RETURNING id INTO v_asset_id;

    UPDATE crop_img.imagery_scenes
    SET raster_asset_id = v_asset_id, status = 'indexed'
    WHERE id = p_scene_id;
  ELSE
    UPDATE crop_img.raster_assets
    SET storage_uri = p_storage_uri, status = 'ready', updated_at = now()
    WHERE id = v_asset_id;

    UPDATE crop_img.imagery_scenes
    SET status = 'indexed'
    WHERE id = p_scene_id;
  END IF;

  INSERT INTO crop_img.field_index_stats (
    scene_id,
    field_id,
    index_name,
    mean_value,
    min_value,
    max_value
  )
  VALUES (
    p_scene_id,
    v_field_id,
    'ndvi',
    p_ndvi_mean,
    p_ndvi_min,
    p_ndvi_max
  )
  ON CONFLICT (scene_id, index_name) DO UPDATE SET
    mean_value = EXCLUDED.mean_value,
    min_value = EXCLUDED.min_value,
    max_value = EXCLUDED.max_value,
    computed_at = now();
END;
$$;
