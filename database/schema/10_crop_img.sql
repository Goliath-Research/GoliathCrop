-- GoliathCrop Phase 3 — imagery scenes, COG raster assets, field index stats
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS crop_img;

CREATE TABLE IF NOT EXISTS crop_img.raster_assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id integer REFERENCES crop_core.fields (id) ON DELETE SET NULL,
  storage_uri text NOT NULL,
  footprint geometry(Polygon, 4326),
  bands text[],
  crs text,
  acquired_at timestamptz,
  source text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  error_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT raster_assets_status_chk
    CHECK (status IN ('pending', 'processing', 'ready', 'failed'))
);

CREATE INDEX IF NOT EXISTS raster_assets_field_acquired_idx
  ON crop_img.raster_assets (field_id, acquired_at DESC);

CREATE TABLE IF NOT EXISTS crop_img.imagery_scenes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id integer NOT NULL REFERENCES crop_core.fields (id) ON DELETE CASCADE,
  raster_asset_id bigint REFERENCES crop_img.raster_assets (id) ON DELETE SET NULL,
  stac_item_id text,
  source text NOT NULL,
  acquired_at timestamptz NOT NULL,
  cloud_fraction double precision,
  status text NOT NULL DEFAULT 'pending',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT imagery_scenes_status_chk
    CHECK (status IN ('pending', 'processing', 'indexed', 'failed'))
);

CREATE INDEX IF NOT EXISTS imagery_scenes_field_acquired_idx
  ON crop_img.imagery_scenes (field_id, acquired_at DESC);

CREATE TABLE IF NOT EXISTS crop_img.field_index_stats (
  scene_id bigint NOT NULL REFERENCES crop_img.imagery_scenes (id) ON DELETE CASCADE,
  field_id integer NOT NULL REFERENCES crop_core.fields (id) ON DELETE CASCADE,
  index_name text NOT NULL,
  mean_value double precision,
  min_value double precision,
  max_value double precision,
  computed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (scene_id, index_name)
);

CREATE OR REPLACE VIEW crop_img.v_scene AS
SELECT
  s.id AS scene_id,
  s.field_id,
  s.acquired_at,
  s.source,
  s.status,
  s.cloud_fraction,
  s.stac_item_id,
  stats.mean_value AS ndvi_mean,
  stats.min_value AS ndvi_min,
  stats.max_value AS ndvi_max,
  ra.storage_uri AS cog_uri
FROM crop_img.imagery_scenes s
LEFT JOIN crop_img.field_index_stats stats
  ON stats.scene_id = s.id AND stats.index_name = 'ndvi'
LEFT JOIN crop_img.raster_assets ra ON ra.id = s.raster_asset_id;

ALTER TABLE crop_img.raster_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_img.imagery_scenes ENABLE ROW LEVEL SECURITY;
ALTER TABLE crop_img.field_index_stats ENABLE ROW LEVEL SECURITY;

