CREATE OR REPLACE FUNCTION crop_img.fn_semantic_scene_list(
  p_user_id integer,
  p_params jsonb,
  p_limit integer
)
RETURNS TABLE (
  scene_id bigint,
  field_id integer,
  acquired_at timestamptz,
  source text,
  ndvi_mean double precision,
  cog_uri text
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = crop_img, crop_core, portal, pg_temp
AS $$
DECLARE
  v_field_id integer;
  v_from timestamptz;
  v_to timestamptz;
  v_lim integer;
BEGIN
  IF p_user_id IS NULL THEN
    RETURN;
  END IF;
  v_field_id := (p_params->>'field_id')::integer;
  IF v_field_id IS NULL THEN
    PERFORM portal.fn_semantic_raise('GS501', 'field_id is required');
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM crop_core.fields fld
    WHERE fld.id = v_field_id
      AND crop_core.fn_user_can_access_farm(p_user_id, fld.farm_id)
  ) THEN
    PERFORM portal.fn_semantic_raise('GS403', 'field scope denied');
  END IF;
  v_from := NULLIF(p_params->>'from', '')::timestamptz;
  v_to := NULLIF(p_params->>'to', '')::timestamptz;
  v_lim := GREATEST(0, COALESCE(p_limit, 500));
  RETURN QUERY
  SELECT
    v.scene_id,
    v.field_id,
    v.acquired_at,
    v.source,
    v.ndvi_mean,
    v.cog_uri
  FROM crop_img.v_scene v
  WHERE v.field_id = v_field_id
    AND (v_from IS NULL OR v.acquired_at >= v_from)
    AND (v_to IS NULL OR v.acquired_at <= v_to)
  ORDER BY v.acquired_at DESC
  LIMIT v_lim;
END;
$$;

CREATE OR REPLACE FUNCTION crop_img.sp_register_drone_upload(
  p_field_id integer,
  p_storage_uri text,
  p_acquired_at timestamptz DEFAULT NULL,
  p_footprint_wkt text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = crop_img, crop_wf, pg_temp
AS $$
DECLARE
  v_asset_id bigint;
  v_scene_id bigint;
  v_geom geometry(Polygon, 4326);
BEGIN
  IF p_field_id IS NULL OR p_storage_uri IS NULL OR btrim(p_storage_uri) = '' THEN
    RAISE EXCEPTION 'field_id and storage_uri are required';
  END IF;
  IF p_footprint_wkt IS NOT NULL AND btrim(p_footprint_wkt) <> '' THEN
    v_geom := ST_SetSRID(ST_GeomFromText(p_footprint_wkt), 4326);
  END IF;
  INSERT INTO crop_img.raster_assets (
    field_id,
    storage_uri,
    footprint,
    source,
    acquired_at,
    status
  )
  VALUES (
    p_field_id,
    p_storage_uri,
    v_geom,
    'drone',
    COALESCE(p_acquired_at, now()),
    'pending'
  )
  RETURNING id INTO v_asset_id;

  INSERT INTO crop_img.imagery_scenes (
    field_id,
    raster_asset_id,
    source,
    acquired_at,
    status,
    metadata
  )
  VALUES (
    p_field_id,
    v_asset_id,
    'drone',
    COALESCE(p_acquired_at, now()),
    'pending',
    jsonb_build_object('upload_uri', p_storage_uri)
  )
  RETURNING id INTO v_scene_id;

  PERFORM crop_wf.sp_enqueue_processing_task(
    'crop.imagery.process',
    jsonb_build_object('scene_id', v_scene_id, 'raster_asset_id', v_asset_id),
    'crop.imagery',
    'drone_upload_registered',
    'drone:' || v_scene_id::text
  );

  RETURN v_scene_id;
END;
$$;

